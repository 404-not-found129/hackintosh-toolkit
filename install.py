def _self_elevate():
    """
    Re-execs this same script elevated if it isn't already - the one thing
    a truly single-file, one-click installer needs to handle itself rather
    than asking the user to remember `sudo`/"Run as Administrator". Does
    NOT suppress the OS's own elevation prompt (sudo password / UAC dialog)
    - that prompt is Windows/sudo's own security boundary, not this
    toolkit's, and bypassing it would be a real security regression, not a
    convenience.
    """
    if os.name == 'nt':
        if ctypes.windll.shell32.IsUserAnAdmin():
            return
        print('Not running as Administrator - relaunching elevated (accept the UAC prompt)...')
        params = subprocess.list2cmdline([os.path.abspath(__file__)] + sys.argv[1:])
        ret = ctypes.windll.shell32.ShellExecuteW(None, 'runas', sys.executable, params, None, 1)
        if int(ret) <= 32:
            raise SystemExit(
                'Could not relaunch elevated (UAC declined, or failed to launch) - '
                're-run this script yourself from an elevated PowerShell/Command Prompt instead.'
            )
        sys.exit(0)
    else:
        if os.geteuid() == 0:
            return
        print('Not running as root - relaunching with sudo (you may be asked for your password)...')
        os.execvp('sudo', ['sudo', sys.executable, os.path.abspath(__file__)] + sys.argv[1:])


